func TestSplitPortableFilenameKeepsSubtitleLanguage(t *testing.T) {
	tests := []struct{ name, stem, ext string }{
		{"2026-10-11 Title-abcdefghijk.en.vtt", "2026-10-11 Title-abcdefghijk", ".en.vtt"},
		{"Title-abcdefghijk.en-US.srt", "Title-abcdefghijk", ".en-US.srt"},
		{"Title-abcdefghijk.zh-Hans.vtt", "Title-abcdefghijk", ".zh-Hans.vtt"},
		{"Title-abcdefghijk.en-orig.vtt", "Title-abcdefghijk", ".en-orig.vtt"},
		{"Title-abcdefghijk.vtt", "Title-abcdefghijk", ".vtt"},
		{"Title-abcdefghijk.mp4", "Title-abcdefghijk", ".mp4"},
		{"Title-abcdefghijk.info.json", "Title-abcdefghijk", ".info.json"},
		// A dotted title isn't mistaken for a language tag.
		{"feat.Me-ab-cd_efghij.mp4", "feat.Me-ab-cd_efghij", ".mp4"},
	}
	for _, tt := range tests {
		stem, ext := splitPortableFilename(tt.name)
		if stem != tt.stem || ext != tt.ext {
			t.Errorf("splitPortableFilename(%q) = %q, %q; want %q, %q", tt.name, stem, ext, tt.stem, tt.ext)
		}
	}
}

