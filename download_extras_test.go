func TestDownloadSavesSubtitlesAndKeepsLanguageSuffixWhenRenaming(t *testing.T) {
	script, argsLog := fakeExtrasYtDlp(t, extrasInfo, writeDownload+`
printf 'WEBVTT' > "$base.en.vtt"
printf 'WEBVTT' > "$base.pt-BR.vtt"
printf 'abcdefghijk\tExtras Test\n'
`)
	cfg := extrasConfig(t, script)
	cfg.Subtitles = SubtitlesConfig{Enabled: true, Languages: "en,pt-BR", AutoGenerated: true}

	result, err := NewDownloader(cfg).DownloadVideo("https://www.youtube.com/watch?v=abcdefghijk", "abcdefghijk", "Extras Channel", "", "mp4", false, false)
	if err != nil || !result.Downloaded {
		t.Fatalf("DownloadVideo() = %+v, %v", result, err)
	}

	runs := invocations(t, argsLog)
	if len(runs) != 1 {
		t.Fatalf("yt-dlp ran %d times, want 1", len(runs))
	}
	args := runs[0]
	if !hasArg(args, "--write-subs") || !hasArg(args, "--write-auto-subs") || argAfter(args, "--sub-langs") != "en,pt-BR" || argAfter(args, "--sub-format") != "vtt/srt/best" {
		t.Fatalf("subtitle args missing: %q", args)
	}
	if hasArg(args, "--sponsorblock-mark") || hasArg(args, "--progress") {
		t.Fatalf("unexpected extras in args: %q", args)
	}
	if args[len(args)-1] != "https://www.youtube.com/watch?v=abcdefghijk" {
		t.Fatalf("URL must stay the last argument, got %q", args[len(args)-1])
	}

	channelDir := filepath.Join(cfg.DownloadDir, "Extras_Channel")
	want := []string{extrasStem + ".en.vtt", extrasStem + ".info.json", extrasStem + ".jpg", extrasStem + ".mp4", extrasStem + ".nfo", extrasStem + ".pt-BR.vtt"}
	if got := dirNames(t, channelDir); strings.Join(got, "|") != strings.Join(want, "|") {
		t.Fatalf("files = %q\nwant %q", got, want)
	}
	// Subtitle files are sidecars, not extra copies of the video.
	if n := NewDownloader(cfg).countVideoFiles(channelDir, "abcdefghijk"); n != 1 {
		t.Fatalf("countVideoFiles = %d, want 1", n)
	}
	if got := findVideoFileForID(channelDir, "abcdefghijk"); filepath.Base(got) != extrasStem+".mp4" {
		t.Fatalf("findVideoFileForID = %q", got)
	}
}

func TestDownloadOmitsSubtitleArgsWhenDisabledOrManualOnly(t *testing.T) {
	script, argsLog := fakeExtrasYtDlp(t, extrasInfo, writeDownload+`printf 'abcdefghijk\tExtras Test\n'`)
	cfg := extrasConfig(t, script)

	cfg.Subtitles = SubtitlesConfig{Enabled: false, Languages: "en", AutoGenerated: true}
	if _, err := NewDownloader(cfg).DownloadVideo("https://www.youtube.com/watch?v=abcdefghijk", "abcdefghijk", "Extras Channel", "", "mp4", false, false); err != nil {
		t.Fatal(err)
	}
	cfg.Subtitles = SubtitlesConfig{Enabled: true, Languages: "en", AutoGenerated: false}
	cfg.DownloadDir = t.TempDir()
	if _, err := NewDownloader(cfg).DownloadVideo("https://www.youtube.com/watch?v=abcdefghijk", "abcdefghijk", "Extras Channel", "", "mp4", false, false); err != nil {
		t.Fatal(err)
	}

	runs := invocations(t, argsLog)
	if hasArg(runs[0], "--write-subs") || hasArg(runs[0], "--sub-langs") {
		t.Fatalf("subtitles disabled but args = %q", runs[0])
	}
	if !hasArg(runs[1], "--write-subs") || hasArg(runs[1], "--write-auto-subs") {
		t.Fatalf("uploaded-only subtitles args = %q", runs[1])
	}
}

func TestDownloadRetriesWithoutSubtitlesWhenSubtitleRequestFails(t *testing.T) {
	// yt-dlp aborts the whole download when YouTube rate-limits the caption request.
	script, argsLog := fakeExtrasYtDlp(t, extrasInfo, `
case "$args" in *--write-subs*)
  echo "ERROR: Unable to download video subtitles for 'en': HTTP Error 429: Too Many Requests" >&2
  exit 1;;
esac
`+writeDownload+`printf 'abcdefghijk\tExtras Test\n'`)
	cfg := extrasConfig(t, script)

	result, err := NewDownloader(cfg).DownloadVideo("https://www.youtube.com/watch?v=abcdefghijk", "abcdefghijk", "Extras Channel", "", "mp4", false, false)
	if err != nil || !result.Downloaded {
		t.Fatalf("DownloadVideo() = %+v, %v; want the video downloaded without subtitles", result, err)
	}
	runs := invocations(t, argsLog)
	if len(runs) != 2 || !hasArg(runs[0], "--write-subs") || hasArg(runs[1], "--write-subs") || hasArg(runs[1], "--sub-langs") {
		t.Fatalf("runs = %q, want a subtitle run then one without subtitles", runs)
	}
}

