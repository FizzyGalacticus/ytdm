func TestDownloadReportsProgressAndKeepsOutputParsing(t *testing.T) {
	script, argsLog := fakeExtrasYtDlp(t, extrasInfo, writeDownload+`
printf '@@ytdm-progress downloading|500|1000|NA|2048.5|3|avc1|none\n'
printf '@@ytdm-progress finished|1000|1000|NA|NA|NA|avc1|none\n'
printf '@@ytdm-progress downloading|10|NA|200|NA|NA|none|opus\n'
printf '@@ytdm-postprocess started|Merger\n' >&2
printf '@@ytdm-postprocess finished|Merger\n' >&2
printf 'WARNING: harmless\n' >&2
printf 'abcdefghijk\tExtras Test\n'
`)
	cfg := extrasConfig(t, script)

	var mu sync.Mutex
	var events []DownloadProgress
	opts := DownloadOptions{OnProgress: func(p DownloadProgress) {
		mu.Lock()
		events = append(events, p)
		mu.Unlock()
	}}
	result, err := NewDownloader(cfg).DownloadVideoWithOptions("https://www.youtube.com/watch?v=abcdefghijk", "abcdefghijk", "Extras Channel", "", "mp4", false, false, opts)
	if err != nil || !result.Downloaded || result.VideoID != "abcdefghijk" || result.VideoTitle != "Extras Test" {
		t.Fatalf("DownloadVideoWithOptions() = %+v, %v", result, err)
	}

	args := invocations(t, argsLog)[0]
	if !hasArg(args, "--progress") || !hasArg(args, "--newline") || argAfter(args, "--progress-delta") != "1" {
		t.Fatalf("progress args missing: %q", args)
	}

	mu.Lock()
	defer mu.Unlock()
	var stages []string
	for _, e := range events {
		stages = append(stages, fmt.Sprintf("%s/%s/%d/%d", e.Phase, e.Stage, e.DownloadedBytes, e.TotalBytes))
	}
	// stdout and stderr are read concurrently, so only check that every event arrived.
	sort.Strings(stages)
	want := []string{"downloading/audio/10/200", "downloading/video/1000/1000", "downloading/video/500/1000", "processing/merging/0/0"}
	if strings.Join(stages, " ") != strings.Join(want, " ") {
		t.Fatalf("progress events = %q, want %q", stages, want)
	}
}

func TestDownloadWithSponsorBlockReadsChaptersFromFileForNFO(t *testing.T) {
	script, _ := fakeExtrasYtDlp(t, extrasInfo, writeDownload+`printf 'abcdefghijk\tExtras Test\n'`)
	cfg := extrasConfig(t, script)

	probe := filepath.Join(t.TempDir(), "fake-ffprobe.sh")
	probeOut := `{"chapters":[{"start_time":"0.000000","end_time":"4.013000","tags":{"title":"[SponsorBlock]: Sponsor"}},{"start_time":"4.013000","end_time":"252.000000","tags":{"title":"Main <Part> & more"}}]}`
	if err := os.WriteFile(probe, []byte("#!/bin/sh\ncat <<'EOF'\n"+probeOut+"\nEOF\n"), 0755); err != nil {
		t.Fatal(err)
	}
	saved := ffprobePath
	ffprobePath = probe
	t.Cleanup(func() { ffprobePath = saved })

	if _, err := NewDownloader(cfg).DownloadVideoWithOptions("https://www.youtube.com/watch?v=abcdefghijk", "abcdefghijk", "Extras Channel", "", "mp4", false, false, DownloadOptions{SponsorBlockMark: true}); err != nil {
		t.Fatal(err)
	}
	nfo, err := os.ReadFile(filepath.Join(cfg.DownloadDir, "Extras_Channel", extrasStem+".nfo"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"[SponsorBlock]: Sponsor", "Main &lt;Part&gt; &amp; more"} {
		if !strings.Contains(string(nfo), want) {
			t.Fatalf("NFO missing chapter %q:\n%s", want, nfo)
		}
	}
}

