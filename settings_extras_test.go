func TestLoadConfigDefaultsSubtitlesOnForOlderConfigFiles(t *testing.T) {
	path := filepath.Join(t.TempDir(), "config.json")
	os.WriteFile(path, []byte(`{"retention_days": 9}`), 0644)
	cfg, err := LoadConfig(path)
	if err != nil {
		t.Fatal(err)
	}
	if want := defaultSubtitlesConfig(); cfg.Subtitles != want {
		t.Fatalf("subtitles = %+v, want defaults %+v", cfg.Subtitles, want)
	}

	os.WriteFile(path, []byte(`{"subtitles": {"enabled": false, "languages": "", "auto_generated": false}}`), 0644)
	cfg, err = LoadConfig(path)
	if err != nil {
		t.Fatal(err)
	}
	if cfg.Subtitles.Enabled || cfg.Subtitles.AutoGenerated || cfg.Subtitles.Languages != "en" {
		t.Fatalf("explicit settings not kept: %+v", cfg.Subtitles)
	}

	// Saving and reloading round-trips the section.
	cfg.Subtitles = SubtitlesConfig{Enabled: true, Languages: "en,es", AutoGenerated: false}
	if err := cfg.Save(path); err != nil {
		t.Fatal(err)
	}
	if err := cfg.ReloadFromDisk(path); err != nil {
		t.Fatal(err)
	}
	if cfg.Subtitles != (SubtitlesConfig{Enabled: true, Languages: "en,es", AutoGenerated: false}) {
		t.Fatalf("after reload: %+v", cfg.Subtitles)
	}
}

func TestNormalizeSubtitleLanguages(t *testing.T) {
	good := map[string]string{
		"en":              "en",
		" en , es ,":      "en,es",
		"en.*,-live_chat": "en.*,-live_chat",
		"pt-BR,zh-Hans":   "pt-BR,zh-Hans",
		"en,,  ,de":       "en,de",
	}
	for in, want := range good {
		got, err := normalizeSubtitleLanguages(in)
		if err != nil || got != want {
			t.Errorf("normalizeSubtitleLanguages(%q) = %q, %v; want %q", in, got, err, want)
		}
	}
	for _, bad := range []string{"", " , ", "en es", "en;rm -rf", "--exec=x y"} {
		if got, err := normalizeSubtitleLanguages(bad); err == nil {
			t.Errorf("normalizeSubtitleLanguages(%q) = %q, want an error", bad, got)
		}
	}
}

func TestConfigAPISubtitles(t *testing.T) {
	dir := t.TempDir()
	wd, _ := os.Getwd()
	os.Chdir(dir)
	t.Cleanup(func() { os.Chdir(wd) })
	os.MkdirAll("data", 0755)

	cfg := newTestConfig(t)
	api := &APIServer{config: cfg, storage: newTestStorage(t)}

	put := func(body string) *httptest.ResponseRecorder {
		rec := httptest.NewRecorder()
		api.updateConfig(rec, httptest.NewRequest(http.MethodPut, "/api/config", strings.NewReader(body)))
		return rec
	}

	if rec := put(`{"subtitles": {"enabled": false, "languages": " en, de ", "auto_generated": false}}`); rec.Code != http.StatusOK {
		t.Fatalf("PUT = %d %s", rec.Code, rec.Body.String())
	}
	if cfg.Subtitles != (SubtitlesConfig{Enabled: false, Languages: "en,de", AutoGenerated: false}) {
		t.Fatalf("subtitles after PUT = %+v", cfg.Subtitles)
	}

	if rec := put(`{"subtitles": {"languages": "en; bad"}}`); rec.Code != http.StatusBadRequest {
		t.Fatalf("bad languages PUT = %d", rec.Code)
	}
	if cfg.Subtitles.Languages != "en,de" {
		t.Fatalf("rejected PUT changed languages to %q", cfg.Subtitles.Languages)
	}

	// Partial update keeps the other fields.
	if rec := put(`{"subtitles": {"enabled": true}}`); rec.Code != http.StatusOK {
		t.Fatalf("partial PUT = %d", rec.Code)
	}
	if cfg.Subtitles != (SubtitlesConfig{Enabled: true, Languages: "en,de", AutoGenerated: false}) {
		t.Fatalf("after partial PUT = %+v", cfg.Subtitles)
	}

	rec := httptest.NewRecorder()
	api.getConfig(rec, httptest.NewRequest(http.MethodGet, "/api/config", nil))
	if !bytes.Contains(rec.Body.Bytes(), []byte(`"subtitles":{"enabled":true,"languages":"en,de","auto_generated":false}`)) {
		t.Fatalf("GET config missing subtitles: %s", rec.Body.String())
	}
}

func TestChannelAndVideoSponsorBlockSettingViaAPI(t *testing.T) {
	store := newTestStorage(t)
	api := &APIServer{config: newTestConfig(t), storage: store}

	if err := store.AddChannel(storage.Channel{ID: "UCsb", Name: "SB Channel", URL: "https://www.youtube.com/channel/UCsb", SponsorBlockMark: true}); err != nil {
		t.Fatal(err)
	}
	if ch, _ := store.GetChannel("UCsb"); !ch.SponsorBlockMark {
		t.Fatal("AddChannel didn't store sponsorblock_mark")
	}

	putChannel := func(body string) {
		t.Helper()
		rec := httptest.NewRecorder()
		api.updateChannel(rec, httptest.NewRequest(http.MethodPut, "/api/channels/UCsb", strings.NewReader(body)), "UCsb")
		if rec.Code != http.StatusOK {
			t.Fatalf("PUT channel = %d %s", rec.Code, rec.Body.String())
		}
	}
	// Clients that predate the field leave it alone.
	putChannel(`{"retention_days": 5}`)
	if ch, _ := store.GetChannel("UCsb"); !ch.SponsorBlockMark || ch.RetentionDays != 5 {
		t.Fatalf("after PUT without field: %+v", ch)
	}
	putChannel(`{"retention_days": 5, "sponsorblock_mark": false}`)
	if ch, _ := store.GetChannel("UCsb"); ch.SponsorBlockMark {
		t.Fatal("sponsorblock_mark not cleared")
	}

	if err := store.AddVideo(storage.Video{ID: "vidsb123456", URL: "https://www.youtube.com/watch?v=vidsb123456", Title: "SB Video"}); err != nil {
		t.Fatal(err)
	}
	putVideo := func(body string) {
		t.Helper()
		rec := httptest.NewRecorder()
		api.updateVideo(rec, httptest.NewRequest(http.MethodPut, "/api/videos/vidsb123456", strings.NewReader(body)), "vidsb123456")
		if rec.Code != http.StatusOK {
			t.Fatalf("PUT video = %d %s", rec.Code, rec.Body.String())
		}
	}
	putVideo(`{"retention_days": 3, "sponsorblock_mark": true}`)
	if v, _ := store.GetVideo("vidsb123456"); !v.SponsorBlockMark {
		t.Fatal("video sponsorblock_mark not set")
	}
	putVideo(`{"retention_days": 4}`)
	if v, _ := store.GetVideo("vidsb123456"); !v.SponsorBlockMark || v.RetentionDays != 4 {
		t.Fatalf("after PUT without field: %+v", v)
	}

	// GET /api/channels exposes the field for the edit modal.
	rec := httptest.NewRecorder()
	api.getChannels(rec, httptest.NewRequest(http.MethodGet, "/api/channels", nil))
	var resp struct {
		Data []map[string]any `json:"data"`
	}
	json.Unmarshal(rec.Body.Bytes(), &resp)
	if len(resp.Data) != 1 || resp.Data[0]["sponsorblock_mark"] != false {
		t.Fatalf("GET channels = %s", rec.Body.String())
	}
}

