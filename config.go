// YtDlpConfig holds yt-dlp specific configuration
type YtDlpConfig struct {
	Path                    string `json:"path"`
	UpdateInterval          string `json:"update_interval_seconds"`          // Go duration string (e.g., "24h0m0s")
	CookiesBrowser          string `json:"cookies_browser"`                  // firefox, chrome, or empty to disable
	CookiesFile             string `json:"cookies_file"`                     // path to cookies.txt file
	ExtractorSleepInterval  string `json:"extractor_sleep_interval_seconds"` // Go duration string
	DownloadThroughputLimit string `json:"download_throughput_limit"`
	RestrictFilenames       bool   `json:"restrict_filenames"`
	CacheDir                string `json:"cache_dir"`
}

// SubtitlesConfig controls the subtitle files saved next to each new download.
type SubtitlesConfig struct {
	Enabled bool `json:"enabled"`
	// Languages is a yt-dlp --sub-langs value, e.g. "en" or "en,es".
	Languages string `json:"languages"`
	// AutoGenerated also saves YouTube's automatic captions when a video has no
	// uploaded subtitles in a requested language.
	AutoGenerated bool `json:"auto_generated"`
}

func defaultSubtitlesConfig() SubtitlesConfig {
	return SubtitlesConfig{Enabled: true, Languages: "en", AutoGenerated: true}
}

// Config holds the application configuration
type Config struct {
	sync.RWMutex
	CheckInterval  string `json:"check_interval_seconds"` // Go duration string (e.g., "5m0s")
	RetentionDays  int    `json:"retention_days"`
	DisablePruning bool   `json:"disable_pruning"`
	DownloadDir    string `json:"download_dir"`
	// MediaServerDownloadDir is the download directory as the media server (Jellyfin)
	// sees it, used for the image paths written into NFO files. Empty means the same
	// path as DownloadDir.
	MediaServerDownloadDir string              `json:"media_server_download_dir"`
	FileNamePattern        string              `json:"file_name_pattern"`
	APIPort                int                 `json:"api_port"`
	MaxConcurrent          int                 `json:"max_concurrent_downloads"`
	DefaultVideoFormat     string              `json:"default_video_format"`  // mp4, webm, mkv
	DefaultVideoQuality    string              `json:"default_video_quality"` // best, 1080, 720, 480, 360 (empty = no global preference)
	MaxLogEntries          int                 `json:"max_log_entries"`       // per-scope log ring buffer size
	YtDlp                  YtDlpConfig         `json:"yt_dlp"`
	Notifications          NotificationsConfig `json:"notifications"`
	Subtitles              SubtitlesConfig     `json:"subtitles"`
}

// DefaultConfig returns a Config with default values
func DefaultConfig() *Config {
	return &Config{
		CheckInterval:      "5m0s",
		RetentionDays:      7,
		DisablePruning:     false,
		DownloadDir:        "/app/downloads",
		FileNamePattern:    "%(upload_date>%Y-%m-%d)s %(title)s-%(id)s.%(ext)s",
		APIPort:            8080,
		MaxConcurrent:      3,
		DefaultVideoFormat: "mp4",
		MaxLogEntries:      100,
		YtDlp: YtDlpConfig{
			Path:                    "yt-dlp",
			UpdateInterval:          "24h0m0s",
			ExtractorSleepInterval:  "0s",
			DownloadThroughputLimit: "",
			RestrictFilenames:       false,
			CacheDir:                "data/yt-dlp-cache",
		},
		Notifications: defaultNotificationsConfig(),
		Subtitles:     defaultSubtitlesConfig(),
	}
}

// LoadConfig loads configuration from a JSON file
func LoadConfig(path string) (*Config, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}

	var config Config
	// Pre-fill settings whose defaults are "on", so a config file written before they
	// existed picks up the defaults instead of the zero values.
	config.Subtitles = defaultSubtitlesConfig()
	if err := json.Unmarshal(data, &config); err != nil {
		return nil, err
	}

	applyConfigDefaults(&config)

	return &config, nil
}

// Save saves the configuration to a JSON file
func (c *Config) Save(path string) error {
	data, err := json.MarshalIndent(c, "", "  ")
	if err != nil {
		return err
	}

	return os.WriteFile(path, data, 0644)
}

// ReloadFromDisk reloads configuration from disk into the in-memory config
func (c *Config) ReloadFromDisk(path string) error {
	c.Lock()
	defer c.Unlock()

	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}

	// Decode notifications into fresh values: json.Unmarshal would otherwise reuse the
	// existing webhook slice and maps in place, racing deliveries that hold a snapshot.
	c.Notifications = NotificationsConfig{}
	if err := json.Unmarshal(data, c); err != nil {
		return err
	}

	applyConfigDefaults(c)

	return nil
}

func applyConfigDefaults(c *Config) {
	if c.YtDlp.Path == "" {
		c.YtDlp.Path = "yt-dlp"
	}
	if c.YtDlp.CacheDir == "" {
		c.YtDlp.CacheDir = "data/yt-dlp-cache"
	}
	if c.CheckInterval == "" {
		c.CheckInterval = "5m0s"
	}
	if c.DownloadDir == "" {
		c.DownloadDir = "/app/downloads"
	}
	if c.YtDlp.UpdateInterval == "" {
		c.YtDlp.UpdateInterval = "24h0m0s"
	}
	if c.YtDlp.ExtractorSleepInterval == "" {
		c.YtDlp.ExtractorSleepInterval = "0s"
	}
	if c.DefaultVideoFormat == "" {
		c.DefaultVideoFormat = "mp4"
	}
	if c.Subtitles.Languages == "" {
		c.Subtitles.Languages = "en"
	}
	if c.MaxLogEntries <= 0 {
		c.MaxLogEntries = 100
	}
	applyNotificationDefaults(&c.Notifications)
}

// GetCheckInterval returns the current check interval as time.Duration with locking
func (c *Config) GetCheckInterval() time.Duration {
	c.RLock()
	defer c.RUnlock()
	dur, _ := time.ParseDuration(c.CheckInterval)
	return dur
}

// GetUpdateInterval returns the current yt-dlp update interval as time.Duration with locking
func (c *Config) GetUpdateInterval() time.Duration {
	c.RLock()
	defer c.RUnlock()
	dur, _ := time.ParseDuration(c.YtDlp.UpdateInterval)
	return dur
}

// GetExtractorSleepInterval returns the extractor sleep interval as time.Duration with locking
func (c *Config) GetExtractorSleepInterval() time.Duration {
	c.RLock()
	defer c.RUnlock()
	dur, _ := time.ParseDuration(c.YtDlp.ExtractorSleepInterval)
	return dur
}

// subtitleLanguageRe is one yt-dlp --sub-langs entry: a language code, optionally a
// regex such as "en.*", or an exclusion like "-live_chat".
var subtitleLanguageRe = regexp.MustCompile(`^-?[A-Za-z0-9_.*-]+$`)

// normalizeSubtitleLanguages trims and validates a comma-separated --sub-langs value.
func normalizeSubtitleLanguages(raw string) (string, error) {
	var langs []string
	for _, part := range strings.Split(raw, ",") {
		part = strings.TrimSpace(part)
		if part == "" {
			continue
		}
		if !subtitleLanguageRe.MatchString(part) {
			return "", fmt.Errorf("%q is not a language code (use codes like en or es, separated by commas)", part)
		}
		langs = append(langs, part)
	}
	if len(langs) == 0 {
		return "", fmt.Errorf("at least one language is required")
	}
	return strings.Join(langs, ","), nil
}
